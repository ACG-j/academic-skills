# /// script
# requires-python = ">=3.11"
# dependencies = []
# ///
"""Scaffold a figure project: directory, contract, plotting script skeleton.

The scaffold exists so the contract gets written before the code. A figure whose claim is
recorded has something to be reviewed against; a figure without one gets reviewed against
whatever the reviewer imagines.

Usage:
    uv run sf_init.py fig2 --style nature --claim "Sorted allocation wins above 60% load"
    uv run sf_init.py fig3 --backend tikz --target-mm 89
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import date
from pathlib import Path
from typing import Any

SKILL_ROOT = Path(__file__).resolve().parents[1]
STYLES = SKILL_ROOT / "styles"
MM_PER_INCH = 25.4


def contract_text(figure_id: str, claim: str, style: str, backend: str, width_mm: float, data: str) -> str:
    return f"""# Figure contract — write this BEFORE plotting.
# The cover test: hide the caption, look at the figure. Is the claim still readable?
# The drop test: delete each panel. If the claim survives, that panel is decoration.

figure_id: {figure_id}
core_claim: "{claim}"
backend: {backend}                # matplotlib | tikz | other

panels:
  - id: a
    type: TODO                   # sorted_bar | line | scatter | heatmap | schematic | ...
    defends: "TODO — the sub-claim this panel carries"

hero_panel: a                    # the panel that carries the headline
hierarchy:
  overview: "TODO — where the eye should land first"
  deviation: "TODO — the surprising or key signal"

export: [pdf, svg, png]
source_data: {data}
stats_on_figure: "TODO — CI / error bars / N, or 'none, and here is why'"

target:
  venue: {style}
  column: single                 # single | 1.5 | double | full
  width_mm: {width_mm:g}

# Filled in during review:
review:
  rounds: 0
  blocking_open: 0
  accepted_warnings: []
"""


def mpl_script(figure_id: str, style: str, width_mm: float, height_mm: float, data: str) -> str:
    return f'''# /// script
# requires-python = ">=3.11"
# dependencies = ["matplotlib", "numpy"]
# ///
"""{figure_id} — generated by sf_init.py.

Claim: see contracts/{figure_id}.yaml
Style: {style} ({width_mm:g} mm single column)

Rules that pay off immediately:
  * read data from a file, never inline arrays
  * seed every RNG so reruns match
  * apply the style ONCE, here at the top
  * save a review PNG alongside the vector output
"""
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from pathlib import Path

STYLE_DIR = Path({str(STYLES)!r})
plt.style.use([STYLE_DIR / "base.mplstyle", STYLE_DIR / "{style}.mplstyle"])

MM = 1 / 25.4
OUT = Path(__file__).parent
OUT.mkdir(parents=True, exist_ok=True)

# --- data -----------------------------------------------------------------
# Replace with a real read; the seeded fallback keeps the scaffold runnable.
# df = pd.read_csv(Path({data!r}))
rng = np.random.default_rng(0)
x = np.linspace(0, 10, 24)
y = np.sin(x / 2) + rng.normal(0, 0.05, x.size)
lo, hi = y - 0.15, y + 0.15

# --- figure ---------------------------------------------------------------
fig, ax = plt.subplots(figsize=({width_mm:g} * MM, {height_mm:g} * MM))

ax.plot(x, y, "o-", label="Measurement (N=24)")
ax.fill_between(x, lo, hi, alpha=0.25, linewidth=0, label="95% CI")

ax.set_xlabel("Time $t$ (s)")
ax.set_ylabel("Amplitude $A$ (V)")
ax.legend(loc="upper right")

# --- export ---------------------------------------------------------------
for ext in ("pdf", "svg", "png"):
    fig.savefig(OUT / f"{figure_id}.{{ext}}", dpi=300)
print(f"saved {{OUT}}/{figure_id}.*")
'''


def tikz_script(figure_id: str, width_mm: float) -> str:
    return f"""% {figure_id} — generated by sf_init.py
% Data goes in a separate .dat file written by Python; this file stays editable.
% Compile: uv run sf_tex2png.py {figure_id}.tex -o qa/
\\documentclass[border=2pt]{{standalone}}
\\usepackage{{pgfplots}}
\\pgfplotsset{{compat=1.18}}
\\begin{{document}}
\\begin{{tikzpicture}}
\\begin{{axis}}[
  width={width_mm:g}mm,
  height={width_mm * 0.7:g}mm,
  xlabel={{Time $t$ (s)}},
  ylabel={{Amplitude $A$ (V)}},
  tick label style={{font=\\footnotesize}},
  label style={{font=\\small}},
  legend style={{font=\\footnotesize, at={{(0.98,0.98)}}, anchor=north east}},
  grid=major,
  grid style={{gray!25}},
]
\\addplot[blue, thick, mark=*, mark size=1.5pt] table[x=t, y=y] {{{figure_id}.dat}};
\\addplot[red, thick, dashed] table[x=t, y=lo] {{{figure_id}.dat}};
\\addplot[red, thick, dashed] table[x=t, y=hi] {{{figure_id}.dat}};
\\legend{{Measured, 95\\% CI}}
\\end{{axis}}
\\end{{tikzpicture}}
\\end{{document}}
"""


def dat_writer(figure_id: str) -> str:
    return f'''# /// script
# requires-python = ">=3.11"
# dependencies = ["numpy"]
# ///
"""{figure_id}: write the data file the TikZ figure reads.

Keeping the data in a separate file means the .tex stays hand-editable and the numbers stay
inspectable.
"""
import numpy as np
from pathlib import Path

OUT = Path(__file__).parent
rng = np.random.default_rng(0)
t = np.linspace(0, 10, 24)
y = np.sin(t / 2) + rng.normal(0, 0.05, t.size)

np.savetxt(
    OUT / "{figure_id}.dat",
    np.column_stack([t, y, y - 0.15, y + 0.15]),
    header="t y lo hi",
    comments="",
    fmt="%.6g",
)
print(f"wrote {{OUT}}/{figure_id}.dat")
'''


def readme_text(figure_id: str, style: str, backend: str) -> str:
    return f"""# {figure_id}

Generated by `sf_init.py`.

## Files

| File | Purpose |
|---|---|
| `contracts/{figure_id}.yaml` | what the figure must claim — write this first |
| `figs/{figure_id}/plot.py` | the plotting script |
| `figs/{figure_id}/{figure_id}.png` | review render |
| `qa/` | crops, findings, diffs |

## Workflow

```bash
# 1. implement
uv run figs/{figure_id}/plot.py

# 2. lint
uv run <skill>/scripts/sf_lint.py --all figs/{figure_id}/plot.py

# 3. review — overlay first, then crop what you chose
uv run <skill>/scripts/sf_crop.py --image figs/{figure_id}/{figure_id}.png --overlay -o qa/
uv run <skill>/scripts/sf_crop.py --image figs/{figure_id}/{figure_id}.png --spec qa/crops.json -o qa/r1/tiles

# 4. fix, then diff
uv run <skill>/scripts/sf_diff.py --before qa/r1/{figure_id}.png --after qa/r2/{figure_id}.png -o qa/diff

# 5. export and verify
uv run <skill>/scripts/sf_export.py --script figs/{figure_id}/plot.py --outdir out --snippet {figure_id}
```

Style: `{style}` · Backend: `{backend}`
"""


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("figure_id", help="figure identifier, e.g. fig2")
    parser.add_argument("--style", default="nature", help="journal style name (see sf_style.py --list)")
    parser.add_argument("--backend", default="matplotlib", choices=["matplotlib", "tikz"], help="rendering stack")
    parser.add_argument("--claim", default="TODO — one sentence the figure must defend", help="core claim")
    parser.add_argument("--width-mm", type=float, default=None, help="target column width in mm")
    parser.add_argument("--height-mm", type=float, default=None, help="figure height in mm")
    parser.add_argument("--data", default="data/processed/input.csv", help="source data path")
    parser.add_argument("--outdir", default=".", help="project root")
    parser.add_argument("--force", action="store_true", help="overwrite existing files")
    parser.add_argument("--json", action="store_true", help="JSON only")
    args = parser.parse_args(argv)

    figure_id = args.figure_id
    root = Path(args.outdir).resolve()
    style_file = STYLES / f"{args.style}.mplstyle"
    if not style_file.exists() and args.backend == "matplotlib":
        known = sorted(p.stem for p in STYLES.glob("*.mplstyle") if p.stem != "base")
        print(json.dumps({"ok": False, "error": f"unknown style '{args.style}'; known: {', '.join(known)}"}))
        return 2

    width_mm = args.width_mm
    if width_mm is None:
        width_mm = 89.0
        meta_path = STYLES / "journals.json"
        if meta_path.exists():
            try:
                meta = json.loads(meta_path.read_text(encoding="utf-8"))
                width_mm = float(meta["journals"].get(args.style, {}).get("single_column_mm", 89.0))
            except (KeyError, ValueError, json.JSONDecodeError):
                pass
    height_mm = args.height_mm if args.height_mm is not None else round(width_mm * 0.72, 1)

    paths: dict[str, Path] = {
        "contract": root / "contracts" / f"{figure_id}.yaml",
        "readme": root / f"{figure_id}.md",
    }
    fig_dir = root / "figs" / figure_id
    if args.backend == "matplotlib":
        paths["script"] = fig_dir / "plot.py"
    else:
        paths["script"] = fig_dir / f"{figure_id}.tex"
        paths["data_writer"] = fig_dir / "write_data.py"

    existing = [str(p) for p in paths.values() if p.exists()]
    if existing and not args.force:
        print(json.dumps({"ok": False, "error": "files already exist", "paths": existing, "hint": "use --force"}))
        return 1

    written: list[str] = []
    for path in paths.values():
        path.parent.mkdir(parents=True, exist_ok=True)

    paths["contract"].write_text(
        contract_text(figure_id, args.claim, args.style, args.backend, width_mm, args.data), encoding="utf-8"
    )
    written.append(str(paths["contract"]))

    if args.backend == "matplotlib":
        paths["script"].write_text(mpl_script(figure_id, args.style, width_mm, height_mm, args.data), encoding="utf-8")
    else:
        paths["script"].write_text(tikz_script(figure_id, width_mm), encoding="utf-8")
        assert "data_writer" in paths
        paths["data_writer"].write_text(dat_writer(figure_id), encoding="utf-8")
        written.append(str(paths["data_writer"]))
    written.append(str(paths["script"]))

    paths["readme"].write_text(readme_text(figure_id, args.style, args.backend), encoding="utf-8")
    written.append(str(paths["readme"]))

    for directory in ("qa", "out", "data/processed"):
        (root / directory).mkdir(parents=True, exist_ok=True)

    payload: dict[str, Any] = {
        "ok": True,
        "figure_id": figure_id,
        "style": args.style,
        "backend": args.backend,
        "width_mm": width_mm,
        "height_mm": height_mm,
        "files": written,
        "created_dirs": [str(root / d) for d in ("qa", "out", "data/processed")],
        "next": [
            f"write the claim in {paths['contract'].relative_to(root)}",
            f"uv run {paths['script'].relative_to(root)}",
            f"uv run <skill>/scripts/sf_lint.py --all {paths['script'].relative_to(root)}",
            f"uv run <skill>/scripts/sf_crop.py --image figs/{figure_id}/{figure_id}.png --overlay -o qa/",
        ],
        "date": date.today().isoformat(),
    }
    if not args.json:
        print(f"scaffolded {figure_id} ({args.backend}, {args.style}, {width_mm:g} mm)", file=sys.stderr)
        for path in written:
            print(f"  {path}", file=sys.stderr)
        print("next:", file=sys.stderr)
        for step in payload["next"]:
            print(f"  {step}", file=sys.stderr)
    print(json.dumps(payload, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
